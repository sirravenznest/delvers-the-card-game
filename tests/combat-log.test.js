const assert=require('node:assert/strict');
const C=require('../app/src/main/assets/cards.js');
const E=require('../app/src/main/assets/engine.js');
const P=require('../app/src/main/assets/pvp.js');
const deck=Array(20).fill('Squire');
const g=P.newMatch(44,deck,deck);
assert.equal(g.history[0].kind,'roll');
const firstTurn=g.history.find(h=>h.kind==='turn'),initialLength=g.history.length;
assert.equal(firstTurn.turn,1);
assert.equal(firstTurn.side,g.opening.winner);
const hash=P.hash(g),seed=g.rs;
for(let i=0;i<8;i++)E.log('Event '+i,'info','e');
assert.equal(g.log.length,3,'compact log remains compatible');
assert.equal(g.history.length,initialLength+8,'review history retains opening rolls and older events');
assert.equal(P.hash(g),hash,'logging does not change match state hash');
assert.equal(g.rs,seed,'logging never consumes random rolls');
assert(P.act(g,g.turn,{a:'end'}).ok);
assert.equal(g.history.at(-1).turn,2);
assert.equal(g.history.at(-1).turnSide,g.second);
const u=E.mk(C.BN.Squire);u.o='e';u.hp=1;g.b[0]=u;E.use(g);
E.heal('e',u,100);
assert.equal(g.history.at(-1).kind,'heal');
assert(g.history.at(-1).text.includes('heals '+(u.mhp-1)+' HP'),'logs actual healing, not requested overheal');
E.move('e',0,4);
assert.equal(g.history.at(-1).kind,'move');
assert.equal(g.history.at(-1).side,'e');
assert(g.history.at(-1).text.includes('R1 C1 to R2 C1'));
E.saves(u);
assert.equal(g.history.at(-1).kind,'roll');
assert(g.history.at(-1).text.includes('needs '+u.save+'+'));
E.dmg('e',u,100);
assert.equal(g.history.at(-2).kind,'damage');
assert(g.history.at(-2).text.includes('0/'+u.mhp+' HP'));
assert.equal(g.history.at(-1).kind,'status');
assert(P.act(g,'p',{a:'resign'}).ok);
assert.equal(g.history.at(-1).kind,'result');
for(let i=0;i<E.LOG_LIMIT+10;i++)E.log('Bounded '+i);
assert.equal(g.history.length,E.LOG_LIMIT);
assert(g.historyDropped>0);
assert.equal(g.history.at(-1).id,g.historySeq);
assert.equal(g.history[0].id,g.historySeq-E.LOG_LIMIT+1);
console.log('PASS combat log history, turn/seat attribution, actual HP changes, rolls and bounded retention');
